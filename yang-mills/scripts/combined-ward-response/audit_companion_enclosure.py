"""Audit all retained coordinate tensors and the exact final error budgets.

This is an aggregate audit, not an independent processor/BLAS verification.
Integer input induction and floating tensor propagation remain as documented.
"""
import hashlib
import json
from fractions import Fraction as F
from math import factorial
from pathlib import Path

import numpy as np

import check_companion_enclosure as ce
import check_signed_retained_enclosure as sr
from check_companion_functional import products, scalar_weight
from check_continuum_pure_sectors import operators

ROOT = Path(__file__).parent
PATH = ROOT/'companion-enclosure-certificate.json'
OUTPUT = ROOT/'companion-enclosure-audit.json'


def nested(x):
    return tuple(nested(y) for y in x) if isinstance(x, list) else x


def frac(x):
    return F(int(x['num']), int(x['den']))


def interval(x):
    lo, hi = int(x['lo']), int(x['hi'])
    assert lo <= hi
    return sr.I(lo, hi)


def main():
    data = json.loads(PATH.read_text())
    assert data['status'] == 'PASS' and not data['failures']
    assert int(data['scale']) == sr.S and data['cutoff'] == 112 and data['degree'] == 12
    assert data['implementation_sha256'] == hashlib.sha256((ROOT/'check_companion_enclosure.py').read_bytes()).hexdigest()
    assert data['input_sha256'] == hashlib.sha256((ROOT/'stored-fourier-enclosure-certificate.json').read_bytes()).hexdigest()
    assert len(data['roots']) == 12 and len(data['mapped_rule']) == 276
    last = -sr.S
    for row in data['roots']:
        root, weight = interval(row['root']), interval(row['weight'])
        assert last < root.lo < root.hi < sr.S and weight.lo > 0
        assert sr.sign(root.lo) == row['sign_lo']
        assert sr.sign(root.hi) == row['sign_hi'] == -row['sign_lo']
        assert root.hi-root.lo <= sr.S//10**50
        last = root.hi
    assert {(r['panel'], r['node']) for r in data['mapped_rule']} == {(p, n) for p in range(23) for n in range(12)}
    dr = []
    for row in data['mapped_rule']:
        v, w, ws = [interval(row[k]) for k in ('v', 'weight_r', 'weight_s')]
        assert v.lo > 0 and w.lo > 0
        expected = v*w
        assert ws.lo <= expected.lo <= expected.hi <= ws.hi
        dr.append(sr.midpoint_radius(w))
    dr = tuple(np.asarray(dr).T)
    heat_count = 0
    assert len(data['heat_enclosures']) == 277
    for row in data['heat_enclosures']:
        assert len(row) == 113
        for entry in row:
            h = interval(entry)
            assert 0 <= h.lo <= h.hi <= sr.S
            heat_count += 1
    assert F(27, 64)*256 == 108 and F(3*112**2, 4*2**14) < 1
    G = F(float.fromhex(data['arithmetic_model']['dot_gamma_upper']))
    assert G > F(554, 2**53-554)
    assert F(float(1-float(G))) < 1-F(554, 2**53-554)
    assert F(float(1e-15)) > F(1, 2**53-1)
    assert F(float.fromhex(data['arithmetic_model']['additive_error_per_operation'])) > 1000*F(2)**(-1022)

    qs, _, _ = operators((1, 3))
    ops = [products(q, r) for q in qs for r in (scalar_weight(), qs[0])]
    expected = {(axis, key[axis]) for op in ops for key in op for axis in range(4)}
    coverage = [(row['axis'], nested(row['key'])) for row in data['feature_coverage']]
    assert len(set(coverage)) == len(coverage) and set(coverage) == expected
    expected_weak = {(axis, feature) for axis, key in expected for feature in key}
    weak_seen, weak_count = set(), 0
    for row in data['weak_enclosures']:
        key = row['axis'], tuple(row['feature'])
        size = 1 if row['axis'] == 0 else 112
        assert key in expected_weak and len(row['entries']) == size
        for entries in row['entries']:
            assert len(entries) == size
            for entry in entries:
                interval(entry); weak_count += 1
        weak_seen.add(key)
    assert weak_seen == expected_weak
    # Weak features occur in more than one product record; every occurrence
    # was generated by the same cached enclosure, and is checked above.
    tables, baseline, tensor_count = {}, {}, 0
    files = {r['path']: r['sha256'] for r in data['feature_files']}
    assert set(files) == {f'companion-enclosure-axis{j}.npz' for j in range(4)}
    for axis in range(4):
        path = ROOT/f'companion-enclosure-axis{axis}.npz'
        assert hashlib.sha256(path.read_bytes()).hexdigest() == files[path.name]
        with np.load(path) as archive:
            expected_names = set()
            for row in data['feature_coverage']:
                if row['axis'] != axis:
                    continue
                key = nested(row['key'])
                name = f"feature{row['index']}"
                names = name+'_center', name+'_radius'
                expected_names.update(names)
                center, radius = [archive[n] for n in names]
                assert center.shape == radius.shape == (276, 276)
                assert np.all(np.isfinite(center)) and np.all(np.isfinite(radius)) and np.all(radius >= 0)
                tables[axis, key] = center, radius
                baseline[axis, key] = F(float.fromhex(row['initial_absolute_upper_hex']))
                assert baseline[axis, key] >= 0
                tensor_count += center.size
            assert set(archive.files) == expected_names
    eps = F(factorial(12)**4, 25*factorial(24)**3)*(1+22*factorial(25))
    eps += 1/sum((F(108)**j/F(factorial(j)) for j in range(161)), F(0))
    assert frac(data['inverse_linear_relative_error']) == eps
    tails, evidence = ce.tail_bounds()
    assert evidence == data['spectral_tail_evidence']
    assert len(data['final']) == 4
    displayed_traces = [('148.83170', '148.83172'), ('111.03741', '111.03743'),
                        ('-147.77981', '-147.77978'), ('-32.21998', '-32.21996')]
    for slot, (op, row) in enumerate(zip(ops, data['final'])):
        assert (row['probe'], row['trace']) == ((3, 6)[slot//2], ('A', 'B')[slot%2])
        assert row['terms'] == len(op)
        local = np.zeros((276, 276)), np.zeros((276, 276))
        absolute = F(0)
        for key, v in sorted(op.items()):
            value = tables[0, key[0]]
            envelope = baseline[0, key[0]]
            for axis in range(1, 4):
                value = sr.multiply(value, tables[axis, key[axis]])
                envelope *= baseline[axis, key[axis]]
            local = sr.add(local, sr.multiply(value, sr.midpoint_radius(sr.rat(v))))
            absolute += abs(v)*envelope
        center, radius = sr.dot(sr.dot(dr, local), dr)
        assert float(center).hex() == row['center_hex'] and float(radius).hex() == row['radius_hex']
        c, r = F(float(center)), F(float(radius))
        assert absolute == frac(row['absolute_initial_upper'])
        weight = absolute*F(64, 27)**2*(2*eps+eps**2)
        error = r+weight+tails[slot//2]
        assert weight == frac(row['weight_error']) and tails[slot//2] == frac(row['spectral_tail'])
        assert error == frac(row['total_error'])
        assert c-error == frac(row['lower']) and c+error == frac(row['upper'])
        assert error < F(1, 100000)
        assert F(displayed_traces[slot][0]) < c-error < c+error < F(displayed_traces[slot][1])
    for i, row in enumerate(data['comparisons']):
        a, b = data['final'][2*i:2*i+2]
        jl = 16*frac(a['lower'])+24*min(F(0), frac(b['lower']))
        jh = 16*frac(a['upper'])+24*max(F(0), frac(b['upper']))
        assert jl == frac(row['J_lower']) and jh == frac(row['J_upper'])
        assert jh < F(row['required_J_upper_below']) and row['separated']
        displayed_J = [('2381.30', '5046.21'), ('-3137.76', '-2364.47')][i]
        assert F(displayed_J[0]) < jl < jh < F(displayed_J[1])
    result = dict(passed=True, certificate_sha256=hashlib.sha256(PATH.read_bytes()).hexdigest(),
                  exact_roots_checked=12, mapped_records_checked=276,
                  heat_entries_checked=heat_count, weak_entry_occurrences_checked=weak_count,
                  distinct_weak_features_checked=len(weak_seen),
                  coordinate_feature_tables_checked=len(coverage),
                  coordinate_tensor_entries_checked=tensor_count,
                  exact_final_budgets_checked=4, probe_separations_checked=2,
                  actual_trace_errors_upper=[sr.display(frac(r['total_error'])) for r in data['final']],
                  required_trace_error_below='1/100000', failures=[],
                  qualification='Complete aggregate audit; interval induction and IEEE tensor model, not independent processor verification.')
    OUTPUT.write_text(json.dumps(result, indent=2)+'\n')
    print('Audit PASS:', len(coverage), 'feature tables;', tensor_count, 'tensor entries;',
          heat_count, 'heat entries;', weak_count, 'weak occurrences;',
          '4 trace errors < 1e-5; 2 separations; failures: []; path:', OUTPUT)


if __name__ == '__main__':
    main()
