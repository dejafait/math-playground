"""Independent complete certificate audit for L099; no large-fiber search."""
from fractions import Fraction
from itertools import combinations
from math import factorial
from pathlib import Path
import json


def main():
    directory = Path(__file__).resolve().parent
    source = json.loads((directory / 'order-three-pole-results.json').read_text())
    checks, failures = [], []

    def check(label, condition):
        checks.append({'label': label, 'passed': bool(condition)})
        if not condition:
            failures.append(label)

    # Factorials, rather than the constructor's comb/Pascal routine.
    Q, n, r = 65537, 1024, 67
    total = factorial(n) // (factorial(r) * factorial(n-r))
    classes = n * Q * Q
    lower = (total + classes - 1) // classes
    ambient, denominator = Q**28, 1 << 128
    scaled = lower * denominator
    expected_fixed = {
        'Q': Q, 'n': n, 'k': 64, 'agreements': r,
        'binomial': total, 'class_count': classes,
        'full_Hayes_class_count': (Q-1)*Q*Q,
        'ceiling_lower': lower, 'threshold_numerator': ambient,
        'threshold_denominator': denominator,
        'positive_threshold_minus_lower_scaled': ambient-scaled,
        'ratio_interval': {'lower_numerator': 1571759,
                           'upper_numerator': 1571760,
                           'denominator': 10**9},
        'strictly_exceeds_threshold': False,
    }
    check('exact fixed schema', set(source['fixed']) == set(expected_fixed))
    for key, value in expected_fixed.items():
        check('complete fixed value: ' + key, source['fixed'][key] == value)
    margins = {
        'ceiling_strict_lower': total-(lower-1)*classes,
        'ceiling_weak_upper': lower*classes-total,
        'threshold_strict_shortfall': ambient-scaled,
        'ratio_weak_lower': 10**9*scaled-1571759*ambient,
        'ratio_strict_upper': 1571760*ambient-10**9*scaled,
    }
    for key, value in margins.items():
        check('integer endpoint: ' + key,
              value >= 0 if key in ('ceiling_weak_upper', 'ratio_weak_lower')
              else value > 0)
    check('full/container class index', (Q-1)*Q*Q == 64*classes)
    generator = pow(3, 64, Q)
    check('recorded subgroup generator', generator == 19139)
    check('generator has exact order 1024',
          pow(generator, 1024, Q) == 1 and pow(generator, 512, Q) == Q-1)
    literal_lower = int(
        '3358693166267948129426257121648891065808354728156229705841256240561653258075795827260997640055')
    check('full manuscript ceiling', lower == literal_lower)
    check('manuscript radius', n-r == 957)

    # Independent elementary-symmetric reconstruction, not iterative polynomial
    # multiplication. In F_17: g=X^5-e1 X^4+e2 X^3-e3 X^2+e4 X-e5,
    # so (a,b,c)=(-e3,e4,-e5) and f=-e2+e1 X.
    p = 17
    H = [x for x in range(1, p) if pow(x, 8, p) == 1]
    check('all small subgroup elements', H == source['small']['H'])
    check('proper order-eight subgroup generated by nine',
          len(H) == 8 and set(H) == {pow(9, j, p) for j in range(8)})
    predicted, subsets = {}, []
    for roots in combinations(H, 5):
        elementary = []
        for size in range(1, 6):
            value = 0
            for part in combinations(roots, size):
                term = 1
                for x in part:
                    term = term*x % p
                value += term
            elementary.append(value % p)
        e1, e2, e3, e4, e5 = elementary
        label = (-e3 % p, e4, -e5 % p)
        message = (-e2 % p, e1)
        predicted.setdefault(label, []).append((roots, message))
        subsets.append({'support': list(roots), 'elementary': elementary,
                        'label': list(label), 'message': list(message)})
        # Check all polynomial coefficients by evaluation at all field points.
        for x in range(p):
            root_value = 1
            for z in roots:
                root_value = root_value*(x-z) % p
            a, b, c = label
            monic_difference = (x**5+a*x*x+b*x+c
                                -x**3*(message[0]+message[1]*x)) % p
            check(f'small complete polynomial: {roots}, x={x}',
                  root_value == monic_difference)
        check(f'small odd constant: {roots}', label[2] in H)

    small = source['small']
    metadata = {'p': p, 'H': H, 'k': 2, 'agreements': 5,
                'subset_count': len(subsets), 'occupied_centers': len(predicted),
                'tested_centers': len(predicted)+2,
                'all_message_count_per_center': p*p}
    check('exact small schema', set(small) == set(metadata) | {'full_lists'})
    for key, value in metadata.items():
        check('complete small metadata: '+key, small[key] == value)

    # Inspect every saved center and every saved candidate. Enumerate all 289
    # scalar messages independently using multiplication by x^3, with no inverse
    # or constructor helper. Also save every full support for these candidates.
    reconstructed, labels = [], []
    for entry in small['full_lists']:
        label = tuple(entry['label'])
        labels.append(label)
        a, b, c = label
        actual = []
        for constant in range(p):
            for slope in range(p):
                support = tuple(x for x in H
                                if (x**3*(constant+slope*x)
                                    -x**5-a*x*x-b*x-c) % p == 0)
                if len(support) >= 5:
                    actual.append((support, (constant, slope)))
        saved = [(tuple(z['support']), tuple(z['message']))
                 for z in entry['candidates']]
        check(f'full saved list: {label}', sorted(saved) == sorted(actual))
        check(f'independent dictionary: {label}',
              sorted(actual) == sorted(predicted.get(label, [])))
        check(f'exactly five agreements: {label}',
              all(len(support) == 5 for support, _ in actual))
        evaluations = [tuple((v[0]+v[1]*x) % p for x in H)
                       for _, v in actual]
        check(f'distinct evaluations: {label}',
              len(evaluations) == len(set(evaluations)))
        reconstructed.append({'label': list(label), 'candidates': [
            {'support': list(s), 'message': list(v)} for s, v in actual]})
    check('no repeated saved centers', len(labels) == len(set(labels)))
    check('every occupied center covered', set(predicted) <= set(labels))
    extras = set(labels)-set(predicted)
    check('one empty inside and one nonzero outside constant',
          len(extras) == 2 and sum(c in H for a, b, c in extras) == 1
          and all(0 <= a < p and 0 <= b < p and 0 < c < p
                  for a, b, c in extras))
    # Audit the claimed constructor coverage count without rerunning its writer.
    check('original 519 check count', source['checks'] == 10+1+56*7+58*2 == 519)
    check('original empty failure list', source['failures'] == [])
    result = {
        'target': 'Independent critical audit of all L099 certificate evidence',
        'fixed_reconstruction': expected_fixed, 'exact_integer_margins': margins,
        'threshold': str(Fraction(ambient, denominator)),
        'lower_over_threshold': str(Fraction(scaled, ambient)),
        'required_unsafe_ratio': '>1',
        'small_subset_reconstruction': subsets,
        'small_full_list_reconstruction': reconstructed,
        'checks': checks, 'check_count': len(checks), 'failures': failures,
        'symbolic_obligations': 'See L099 critical-audit proof; finite checks '
                                'do not establish extension completeness.',
    }
    path = directory / 'order-three-pole-critical-audit.json'
    path.write_text(json.dumps(result, indent=2)+'\n')
    print(f'checks={len(checks)}; failures={len(failures)}; certificate={path}')
    print('actual lower/threshold in [1571759,1571760)/10^9; required >1')
    print(f'complete small evidence: {len(subsets)} subsets, '
          f'{len(labels)} centers, 289 messages per center')
    print('Extension completeness is symbolic; maximum fiber and safety unresolved.')
    if failures:
        print('Failures: '+', '.join(failures))
        raise SystemExit(1)


if __name__ == '__main__':
    main()
